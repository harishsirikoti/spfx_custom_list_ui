/*
 * Generates the locally bundled, scoped icon assets from the pinned @flaticon/flaticon-uicons package.
 *
 *   node scripts/generate-uicons.js
 *
 * Outputs (committed to the repository, regenerated only when the package version changes):
 *   src/webparts/customListUi/icons/uiconNames.ts   list of supported icon names (small, always bundled)
 *   src/webparts/customListUi/icons/uiconStyles.ts  scoped CSS with the font embedded (lazy-loaded chunk)
 *
 * Only the "regular rounded" set (class prefix fi-rr-) is bundled. Every rule is scoped under
 * [data-clui-host] so the icon CSS cannot affect any other element of the SharePoint page.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const packageRoot = path.join(__dirname, '..', 'node_modules', '@flaticon', 'flaticon-uicons');
const outDir = path.join(__dirname, '..', 'src', 'webparts', 'customListUi', 'icons');
const version = JSON.parse(fs.readFileSync(path.join(packageRoot, 'package.json'), 'utf8')).version;

const css = fs.readFileSync(path.join(packageRoot, 'css', 'regular', 'rounded.css'), 'utf8');

// Font file referenced by the original stylesheet.
const fontMatch = /url\(\.\.\/(uicons-regular-rounded-[A-Z0-9]+\.woff2)\)/.exec(css);
if (!fontMatch) {
  throw new Error('woff2 font reference not found in rounded.css');
}
const fontBase64 = fs.readFileSync(path.join(packageRoot, 'css', fontMatch[1])).toString('base64');

// Icon name -> code point.
const icons = [];
const iconPattern = /\.(fi-rr-[a-z0-9]+(?:-[a-z0-9]+)*):before\{content:"\\([0-9a-f]+)"\}/g;
let m;
while ((m = iconPattern.exec(css)) !== null) {
  icons.push({ name: m[1], code: m[2] });
}
if (icons.length < 1000) {
  throw new Error(`Unexpectedly few icons found: ${icons.length}`);
}

const header =
  `// <auto-generated>\n// Generated by scripts/generate-uicons.js from @flaticon/flaticon-uicons ${version}. Do not edit.\n` +
  `// Uicons by Flaticon (https://www.flaticon.com/uicons) - see THIRD-PARTY-NOTICES.md for license terms.\n`;

fs.writeFileSync(
  path.join(outDir, 'uiconNames.ts'),
  `${header}\n/** Names of all bundled Uicons (regular rounded), e.g. "fi-rr-calendar". */\n` +
    `export const UICON_NAMES: string[] = '${icons.map((i) => i.name).join(' ')}'.split(' ');\n`
);

const scope = '[data-clui-host]';
const rules = [
  `@font-face{font-family:"clui-uicons-rr";src:url(data:font/woff2;base64,${fontBase64}) format("woff2");font-display:swap}`,
  `${scope} i[class*="fi-rr-"]::before,${scope} span[class*="fi-rr-"]::before{` +
    'font-family:"clui-uicons-rr"!important;font-style:normal;font-weight:400!important;font-variant:normal;' +
    'text-transform:none;line-height:1;display:inline-block;-webkit-font-smoothing:antialiased;-moz-osx-font-smoothing:grayscale}',
  ...icons.map((i) => `${scope} i.${i.name}::before,${scope} span.${i.name}::before{content:"\\${i.code}"}`)
];

fs.writeFileSync(
  path.join(outDir, 'uiconStyles.ts'),
  `${header}\n/** Scoped Uicons CSS, including the embedded font. Injected once by IconLoader. */\n` +
    `export const UICON_CSS: string = ${JSON.stringify(rules.join('\n'))};\n`
);

console.log(`Generated ${icons.length} icons from @flaticon/flaticon-uicons ${version}.`);
