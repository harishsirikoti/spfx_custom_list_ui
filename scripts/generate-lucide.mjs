/*
 * Generates the Lucide icon catalog used by the <icon> template tag from the pinned lucide-react package.
 *
 *   node scripts/generate-lucide.mjs
 *
 * Outputs (committed; regenerate only when the pinned lucide-react version changes):
 *   src/webparts/customListUi/lucide/lucideNames.ts      icon names + aliases (small, always bundled, used for validation)
 *   src/webparts/customListUi/lucide/lucideIconData.ts   SVG node data of every icon (large, lazy-loaded chunk)
 *
 * Only data is generated. At runtime the data is drawn by Lucide's own React <Icon> component.
 */
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL, fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, '..');
const packageRoot = path.join(root, 'node_modules', 'lucide-react');
const iconsDir = path.join(packageRoot, 'dist', 'esm', 'icons');
const outDir = path.join(root, 'src', 'webparts', 'customListUi', 'lucide');
const version = JSON.parse(fs.readFileSync(path.join(packageRoot, 'package.json'), 'utf8')).version;

const files = fs.readdirSync(iconsDir).filter((f) => f.endsWith('.mjs') && f !== 'index.mjs').sort();
const names = [];
const aliases = {}; // alias -> canonical name
const data = {}; // canonical name -> [[tag, attrs], ...] (the React "key" attribute is dropped and re-added at runtime)

for (const file of files) {
  const name = file.replace(/\.mjs$/, '');
  const source = fs.readFileSync(path.join(iconsDir, file), 'utf8');
  const alias = /export \{ default \} from '\.\/([a-z0-9-]+)\.mjs';/.exec(source);
  if (alias) {
    aliases[name] = alias[1];
    continue;
  }
  const module = await import(pathToFileURL(path.join(iconsDir, file)).href);
  const node = module.__iconData && module.__iconData.node;
  if (!Array.isArray(node)) {
    throw new Error(`No icon data in ${file}`);
  }
  names.push(name);
  data[name] = node.map(([tag, attrs]) => {
    const { key, ...rest } = attrs;
    return [tag, rest];
  });
}

// Every alias must point at a real icon.
for (const [alias, target] of Object.entries(aliases)) {
  if (!data[target]) {
    delete aliases[alias];
  }
}

const header =
  `// <auto-generated>\n// Generated by scripts/generate-lucide.mjs from lucide-react ${version}. Do not edit.\n` +
  `// Lucide icons are licensed under the ISC license - see THIRD-PARTY-NOTICES.md.\n`;

const aliasEntries = Object.entries(aliases).map(([a, t]) => `${a}=${t}`);
fs.writeFileSync(
  path.join(outDir, 'lucideNames.ts'),
  `${header}\n/** Version of lucide-react the catalog was generated from. */\nexport const LUCIDE_VERSION: string = '${version}';\n\n` +
    `/** Canonical icon names, for example "calendar-days". */\nexport const LUCIDE_ICON_NAMES: string[] = '${names.join(' ')}'.split(' ');\n\n` +
    `/** Alternative (older) names that point to a canonical icon, as "alias=canonical". */\nexport const LUCIDE_ALIAS_ENTRIES: string[] = '${aliasEntries.join(' ')}'.split(' ');\n`
);

const json = JSON.stringify(data).replace(/\\/g, '\\\\').replace(/'/g, "\\'");
fs.writeFileSync(
  path.join(outDir, 'lucideIconData.ts'),
  `${header}\n/** JSON of every icon: { "name": [["path", { "d": "..." }], ...] }. Parsed once, on first use, by iconRegistry. */\n` +
    `export const LUCIDE_ICON_JSON: string = '${json}';\n`
);

console.log(`Generated ${names.length} icons and ${aliasEntries.length} aliases from lucide-react ${version}.`);
